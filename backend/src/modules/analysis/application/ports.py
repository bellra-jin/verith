"""Structural adapter only. Transaction/owner/state orchestration stays in caller."""
from typing import Protocol,runtime_checkable,Any,TYPE_CHECKING
from src.modules.analysis.domain.contracts import FrozenAnalysisResult,StagedReportReference
if TYPE_CHECKING:
    from src.modules.auth.application.session_service import Principal


@runtime_checkable
class AnalysisAdapter(Protocol):
    def build_request(self)->dict[str,Any]:...
    def validate_and_freeze(self,response:Any)->FrozenAnalysisResult:...
    async def stage(self,session:Any,principal:'Principal',frozen:FrozenAnalysisResult)->StagedReportReference:...


class CoordinatorError(ValueError):
    """Fixed public code and analysis ID are supplied by the selected profile."""


class AnalysisRepository(Protocol):
    async def by_key(self,session:Any,owner:Any,key:bytes)->Any:...
    async def owned(self,session:Any,analysis_id:Any,owner:Any)->Any:...
    async def admit(self,session:Any,values:dict)->Any:...
    async def expire(self,session:Any,row:Any)->None:...
    async def accept(self,session:Any,row:Any,claim:bytes,**values:Any)->Any:...


class AnalysisProfile(Protocol):
    operation:str
    deadline_seconds:int
    repository:AnalysisRepository
    preserved_errors:tuple
    admission_errors:tuple
    contract_errors:tuple
    publish_errors:tuple
    snapshot_conflicts:tuple
    def confirmed_snapshot_conflict(self,error:Exception)->bool:...
    def parse(self,body:Any)->Any:...
    def normalized(self,body:Any)->str:...
    def input_clock(self,body:Any,stamp:Any)->dict:...
    def spec_json(self)->str:...
    def adapter(self,row:Any,owner:Any)->AnalysisAdapter:...
    def from_stored(self,adapter:AnalysisAdapter,row:Any)->FrozenAnalysisResult:...
    async def dispatch(self,client:Any,request:dict)->dict:...
    def view(self,row:Any)->Any:...
    def error(self,code:str,analysis_id:Any=None)->CoordinatorError:...
    def confirmed_conflict(self,error:Exception)->bool:...
    async def report_exists(self,session:Any,report_id:Any)->bool:...
